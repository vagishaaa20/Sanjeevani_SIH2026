/**
 * Translate text based on the selected target language code ('en', 'hi', 'bn', etc.)
 */
export function getTranslatedText(text, targetLang = 'en') {
    if (!text || targetLang === 'en' || !targetLang) {
        return text;
    }

    const langDict = TRANSLATIONS[targetLang];
    if (langDict && langDict[text]) {
        return langDict[text];
    }

    // Return original text if not explicitly mapped
    return text;
}
